#!/usr/bin/env python3
"""Cost of common batch workloads per model, with and without prompt caching.

Inputs: an HF-dataset snapshot CSV (hf/dataset/data/batch_models_<date>.csv, which carries
cache_pricing) and reference/workloads/workload-profiles.json (per-request token shapes).

Per request, US$ (prices per million tokens, base tier; no profile reaches a long-context override):
  no cache : input * p_in + output * p_out
  cached   : cached = cacheable_prefix * hit_rate if the model publishes a cache read price, else 0
             (input - cached) * p_in
             + cached * (1 - 1/R) * p_read + cached * (1/R) * p_write    R = requests_per_cache_write
             + output * p_out
             p_write = published write price, else p_in.
Reported per 1,000 requests.

Usage: python3 -I workload_costs.py <snapshot.csv> <profiles.json> <out-prefix>
Writes <out-prefix>.csv (long format) and <out-prefix>.md (matrix). Written by Claude Opus 5.5, 2026-10-31.
"""
import csv
import json
import sys

N = 1000


def cost(m, p, cache_cfg, cached_mode):
    pin, pout = float(m["batch_input_usd_per_m"]), float(m["batch_output_usd_per_m"])
    c = json.loads(m["cache_pricing"]) if m["cache_pricing"] else None
    cached = p["cacheable_prefix"] * cache_cfg["best_case_hit_rate"] if (cached_mode and c) else 0
    r = cache_cfg["requests_per_cache_write"]
    pread = c["read_usd_per_m"] if c else 0
    pwrite = (c.get("write_usd_per_m") if c else None) or pin
    usd = ((p["input"] - cached) * pin + cached * (1 - 1 / r) * pread + cached / r * pwrite
           + p["output"] * pout) / 1e6
    return usd * N


def main(snap, prof_path, prefix):
    models = list(csv.DictReader(open(snap, newline="")))
    cfg = json.load(open(prof_path))
    profs, cc = cfg["profiles"], cfg["cache_assumptions"]
    rows = []
    for m in models:
        for p in profs:
            a, b = cost(m, p, cc, False), cost(m, p, cc, True)
            rows.append({"snapshot_date": m["snapshot_date"], "model": m["model"], "tier": m["tier"],
                         "sub_band": m["sub_band"], "offers_cache_pricing": m["offers_cache_pricing"],
                         "profile": p["id"], "input_tokens": p["input"], "output_tokens": p["output"],
                         "cacheable_prefix": p["cacheable_prefix"],
                         "usd_per_1k_requests_no_cache": round(a, 4),
                         "usd_per_1k_requests_cached": round(b, 4),
                         "cache_saving_pct": round(100 * (a - b) / a, 1) if a else 0})
    with open(prefix + ".csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    by = {(r["model"], r["profile"]): r for r in rows}
    ids = [p["id"] for p in profs]
    order = sorted(models, key=lambda m: (float(m["batch_output_usd_per_m"]), float(m["batch_input_usd_per_m"]), m["model"]))
    f2 = lambda v: f"{v:,.0f}" if v >= 100 else f"{v:.1f}" if v >= 10 else f"{v:.2f}" if v >= 0.1 else f"{v:.3f}"
    out = [f"US$ per 1,000 requests, batch prices, best-case cache (no-cache figure in brackets where caching changes it). "
           f"Snapshot {models[0]['snapshot_date']}. Generated by scripts/workload_costs.py.", "",
           "| Model | Sub-band | " + " | ".join(ids) + " |", "| --- | --- | " + " | ".join("---:" for _ in ids) + " |"]
    for m in order:
        cells = []
        for i in ids:
            r = by[(m["model"], i)]
            a, b = r["usd_per_1k_requests_no_cache"], r["usd_per_1k_requests_cached"]
            cells.append(f2(b) + (f" ({f2(a)})" if abs(a - b) > 1e-9 else ""))
        out.append(f"| `{m['model']}` | {m['sub_band']} | " + " | ".join(cells) + " |")
    open(prefix + ".md", "w").write("\n".join(out) + "\n")
    print(prefix + ".csv", len(rows), "rows")


if __name__ == "__main__":
    main(*sys.argv[1:4])
